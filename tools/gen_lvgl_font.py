#!/usr/bin/env python3
"""Generate an LVGL v9 bitmap font (lv_font_fmt_txt, 4 bpp, uncompressed) from a
TTF using Pillow - a local stand-in for lv_font_conv, used for the watch's
reply text, which needs Latin-1 accents (pt-BR) that LVGL's built-in
Montserrat fonts lack. No kerning table; glyph advances come from the font.

Usage: gen_lvgl_font.py FONT.ttf SIZE NAME OUT.c
"""
import sys

from PIL import Image, ImageDraw, ImageFont

# ASCII + Latin-1 supplement + a few typographic extras an LLM tends to emit.
RANGES = [(0x20, 0x7E), (0xA0, 0xFF)]
EXTRAS = [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC]


def render(font, cp):
    ch = chr(cp)
    adv = font.getlength(ch)
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return adv, 0, 0, 0, 0, []
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    # Trim fully empty rows/columns so boxes are tight.
    bbox = img.getbbox()
    if bbox is None:
        return adv, 0, 0, 0, 0, []
    img = img.crop(bbox)
    x0 += bbox[0]
    y1 = y0 + bbox[3]
    w, h = img.size
    px = [v >> 4 for v in img.getdata()]  # 8-bit -> 4-bit
    if len(px) % 2:
        px.append(0)
    data = [(px[i] << 4) | px[i + 1] for i in range(0, len(px), 2)]
    # ofs_y: bottom of the box relative to the baseline, positive up.
    return adv, w, h, x0, -y1, data


def main():
    ttf, size, name, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()

    cps = [cp for a, b in RANGES for cp in range(a, b + 1)] + EXTRAS
    bitmap, dscs = [], []
    for cp in cps:
        adv, w, h, ox, oy, data = render(font, cp)
        dscs.append((cp, len(bitmap), round(adv * 16), w, h, ox, oy))
        bitmap.extend(data)

    L = []
    L.append("/* Generated by tools/gen_lvgl_font.py - do not edit.")
    L.append(f" * {name}: Montserrat Medium {size} px, 4 bpp, U+0020-007E, U+00A0-00FF + extras.")
    L.append(" * Montserrat is licensed under the SIL Open Font License 1.1. */")
    L.append('#include "lvgl.h"\n')
    L.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        L.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) + ",")
    L.append("};\n")
    L.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    L.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
    for cp, idx, adv, w, h, ox, oy in dscs:
        L.append(f"    {{.bitmap_index = {idx}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, "
                 f".ofs_x = {ox}, .ofs_y = {oy}}}, /* U+{cp:04X} */")
    L.append("};\n")

    base = EXTRAS[0]
    L.append("static const uint16_t unicode_list_extras[] = {")
    L.append("    " + ", ".join(f"0x{cp - base:x}" for cp in EXTRAS))
    L.append("};\n")
    gid = 1
    cmaps = []
    for a, b in RANGES:
        cmaps.append(f"    {{.range_start = {a}, .range_length = {b - a + 1}, .glyph_id_start = {gid}, "
                     ".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
                     ".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},")
        gid += b - a + 1
    cmaps.append(f"    {{.range_start = {base}, .range_length = {EXTRAS[-1] - base + 1}, "
                 f".glyph_id_start = {gid}, .unicode_list = unicode_list_extras, "
                 f".glyph_id_ofs_list = NULL, .list_length = {len(EXTRAS)}, "
                 ".type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY},")
    L.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    L.extend(cmaps)
    L.append("};\n")

    L.append(f"""static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = {len(cmaps)},
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
#if LV_VERSION_CHECK(9, 6, 0) || LVGL_VERSION_MAJOR >= 10
    .cap_height = {-font.getbbox("H", anchor="ls")[1]},
    .x_height = {-font.getbbox("x", anchor="ls")[1]},
#endif
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
#if LV_VERSION_CHECK(9, 3, 0)
    .static_bitmap = 1,
#endif
    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};
""")
    with open(out, "w") as f:
        f.write("\n".join(L))
    print(f"{out}: {len(cps)} glyphs, {len(bitmap)} bitmap bytes, line {ascent + descent}px")


if __name__ == "__main__":
    main()
